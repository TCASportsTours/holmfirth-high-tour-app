// Regenerate public/js/tour-default.js (the PUBLIC half only) from an App Database workbook.
// The app shows this bundled copy until the first Publish, and if the server can't be reached.
// Usage: node dev/build-defaults.mjs <path-to-App-Database.xlsx> [--private-out file.json]
// The private half is never written into public/. --private-out is for local testing only.
import fs from "node:fs";
import vm from "node:vm";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const XLSX = require("xlsx");
// parse-db.js is a plain browser script; run it in a sandbox and pick up self.TourDB
const sandbox = { self: {} };
vm.runInNewContext(fs.readFileSync(new URL("../public/js/parse-db.js", import.meta.url), "utf8"), sandbox);
const TourDB = sandbox.self.TourDB;

const [file, flag, privOut] = process.argv.slice(2);
if (!file) { console.error("Usage: node dev/build-defaults.mjs <App-Database.xlsx> [--private-out file.json]"); process.exit(1); }
const wb = XLSX.read(fs.readFileSync(file), { type: "buffer" });
const res = TourDB.parse(XLSX, wb);
res.warnings.forEach((w) => console.warn("warning:", w));
res.public.publishedAt = null; // bundled default, not a publish
res.public.students = []; // the student sign-in list only comes from a Publish, never the public repo
fs.writeFileSync(new URL("../public/js/tour-default.js", import.meta.url),
  "/* Bundled public itinerary — generated by dev/build-defaults.mjs from the App Database. Public data only. */\n" +
  "window.TOUR_DEFAULT = " + JSON.stringify(res.public, null, 1) + ";\n");
console.log(`public: ${res.public.events.length} events, ${res.public.days.length} days, ${res.public.more.length} tiles`);
if (flag === "--private-out" && privOut) {
  fs.writeFileSync(privOut, JSON.stringify(res.private, null, 1));
  console.log(`private: ${res.private.students.length} students -> ${privOut}`);
}
